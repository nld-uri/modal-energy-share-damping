"""Emit the full per-cell table as LaTeX, so no value is transcribed by hand.

The manuscript quotes summary statistics over the map cells and, in an earlier
version, quoted eight of the twenty-five recovered values in ascending mu
without stating how those eight were chosen. This writes every cell, with the
conditioning and fit-quality columns beside each estimate, and the manuscript
\\input{}s the result -- so the table cannot drift from the file it came from.

Usage:  python make_cell_table.py   (writes tables/cell_table.tex)
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
CK = os.path.join(ROOT, "checkpoints")
OUT = os.path.join(ROOT, "tables", "cell_table.tex")

HEAD = r"""% generated by code/verification/make_cell_table.py -- do not edit
\begin{longtable}{rrrrrrrrr}
\caption{Every cell of the bias map and the onset sweep, in ascending
$\mu=k_{3}A^{2}$. Cells with a modal energy share above $0.99$ are the
``single-mode'' set referred to in Section~\ref{sec:below}; the share column
identifies them, so no selection rule is applied to the reader's
disadvantage. $\kappa$ is the condition number of $[\bq\ \dot\bq]$ over the
window and $R^{2}$ that of the log-envelope fit. Three cells appear twice
because the grid and the onset sweep overlap; the repeated values agree to
all digits shown, which is the only reproducibility check available within a
single run.}\label{tab:cells}\\
\toprule
$\mu$ & $k_{3}$ & $A$ & share & $c_{\mathrm{env}}/\ctr$ &
$c_{\mathrm{gcvd}}/\ctr$ & $c_{\mathrm{flux}}/\ctr$ & $\kappa$ & $R^{2}$ \\
\midrule
\endfirsthead
\toprule
$\mu$ & $k_{3}$ & $A$ & share & $c_{\mathrm{env}}/\ctr$ &
$c_{\mathrm{gcvd}}/\ctr$ & $c_{\mathrm{flux}}/\ctr$ & $\kappa$ & $R^{2}$ \\
\midrule
\endhead
\bottomrule
\endfoot
"""


def fmt_mu(mu):
    if mu == 0.0:
        return "$0$"
    e = 0
    m = mu
    while m < 1.0:
        m *= 10.0
        e -= 1
    return rf"${m:.2g}\times10^{{{e}}}$"


def main():
    bm = json.load(open(os.path.join(CK, "bias_map_results.json")))
    cells = sorted(bm["grid"] + bm["threshold_sweep"],
                   key=lambda c: (c["k3"] * c["A"] ** 2, c["k3"]))
    lines = [HEAD]
    for c in cells:
        mu = c["k3"] * c["A"] ** 2
        lines.append(
            f"{fmt_mu(mu)} & ${c['k3']:g}$ & ${c['A']:g}$ & "
            f"${c['e_frac']:.4f}$ & ${c['r_env']:.4f}$ & ${c['r_gcvd']:.4f}$ & "
            f"${c['r_flux']:.4f}$ & ${c['cond']:.0f}$ & "
            f"${c['env_r2']:.5f}$ \\\\\n")
    lines.append("\\end{longtable}\n")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as fh:
        fh.writelines(lines)
    print(f"{len(cells)} cells -> {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
